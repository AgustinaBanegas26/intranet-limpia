create table public.ausencias (
  id bigint generated by default as identity primary key,
  empleado_id bigint references public.empleados(id) on delete cascade,
  tipo text not null,
  fecha_desde date not null,
  fecha_hasta date not null,
  motivo text,
  aprobada boolean not null default false,
  created_at timestamptz not null default now(),
  estado text not null default 'pendiente',
  hora_desde time,
  hora_hasta time,
  archivo_url text,
  archivo_nombre text,
  constraint ausencias_fecha_check check (fecha_hasta >= fecha_desde),
  constraint ausencias_llegada_tarde_horario_check check (
    lower(replace(tipo, ' ', '_')) <> 'llegada_tarde'
